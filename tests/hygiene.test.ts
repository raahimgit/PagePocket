import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

const root = process.cwd();
const walk = (dir: string): string[] =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });

const code = ["src", "tests", "scripts", "e2e", ".github"]
  .flatMap((dir) => walk(join(root, dir)))
  .filter((f) => /\.(ts|mjs|cjs|css|html|ya?ml)$/.test(f) && !f.endsWith("hygiene.test.ts"));

const offenders = (pattern: RegExp) => code.filter((f) => pattern.test(readFileSync(f, "utf8"))).map((f) => f.slice(root.length + 1));

describe("source hygiene", () => {
  it("contains no emoji", () => {
    expect(offenders(/\p{Extended_Pictographic}/u)).toEqual([]);
  });

  it("contains no tool or author attributions", () => {
    expect(offenders(/\b(Claude|Anthropic|ChatGPT|OpenAI|Copilot|generated by|AI-generated)\b/i)).toEqual([]);
  });

  it("has no unfinished-work markers", () => {
    expect(offenders(/\b(TODO|FIXME|XXX|HACK)\b/)).toEqual([]);
  });

  it("has no console output or debugger statements in the extension", () => {
    const src = code.filter((f) => f.includes(`${join(root, "src")}`));
    const hits = src.filter((f) => /\bconsole\.|\bdebugger\b/.test(readFileSync(f, "utf8")));
    expect(hits).toEqual([]);
  });
});
